export const $ = (s, r = document) => r.querySelector(s);
export const icon = n => `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${P[n]}</svg>`;
export const setIcon = (el, n) => (el.innerHTML = icon(n));

/** Aplica marca, tema, textos ([data-t="home.title.0"]), logos e ícones na página. */
export function applyBrand() {
  const root = document.documentElement.style;
  Object.entries(site.theme).forEach(([k, v]) => root.setProperty(k, v));
  root.setProperty('--hero', `url(${site.hero})`);
  document.title = `${site.brand} — ${site.tagline}`;
  document.querySelectorAll('[data-logo]').forEach(i => { i.src = site.logo; i.alt = site.brand; });
  document.querySelectorAll('[data-t]').forEach(el => (el.textContent = el.dataset.t.split('.').reduce((o, k) => o?.[k], site) ?? ''));
  document.querySelectorAll('[data-icon]').forEach(el => setIcon(el, el.dataset.icon));
  const f = $('#features');
  if (f) f.innerHTML = site.home.features.map(x => `<li>${icon(x.icon)}<span>${x.text}</span></li>`).join('');
}
